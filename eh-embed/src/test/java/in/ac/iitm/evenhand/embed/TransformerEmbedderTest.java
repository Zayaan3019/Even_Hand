package in.ac.iitm.evenhand.embed;

import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

/**
 * Our forward pass against the reference: {@code minilm-golden.tsv} holds, for twelve answers
 * (accents, Greek, CJK, newlines, an over-long word, and one answer past the 256-piece limit),
 * the token ids Hugging Face's tokenizer produced and the vector
 * {@code SentenceTransformer.encode(..., normalize_embeddings=True)} returned. Generated by
 * {@code scripts/golden_embeddings.py}.
 *
 * <p>Needs the model on disk; CI fetches it, and a laptop without it skips these checks.
 */
class TransformerEmbedderTest {

    record Golden(String text, int[] ids, float[] vector) {}

    static List<Golden> golden;
    static TransformerEmbedder model;

    @BeforeAll
    static void load() throws IOException {
        golden = new ArrayList<>();
        try (InputStream in = TransformerEmbedderTest.class.getResourceAsStream("/minilm-golden.tsv")) {
            for (String line : new String(in.readAllBytes(), StandardCharsets.UTF_8).split("\n")) {
                if (line.startsWith("#") || line.isBlank()) continue;
                String[] f = line.split("\t");
                String text = f[0].replace("\\n", "\n").replace("\\\\", "\\");
                int[] ids = Arrays.stream(f[1].split(",")).mapToInt(Integer::parseInt).toArray();
                String[] parts = f[2].split(",");
                float[] v = new float[parts.length];
                for (int i = 0; i < v.length; i++) v[i] = Float.parseFloat(parts[i]);
                golden.add(new Golden(text, ids, v));
            }
        }
        for (Path dir : Embedders.searchPath()) {
            if (Files.isRegularFile(dir.resolve("model.safetensors"))
                    && Embedders.verify(dir, Embedders.MINILM).isEmpty()) {
                model = TransformerEmbedder.load(dir, "test");
                return;
            }
        }
    }

    @Test
    @DisplayName("the tokenizer reproduces Hugging Face's ids exactly, truncation included")
    void tokenizerMatchesReference() {
        assumeTrue(model != null, "embedding model not installed");
        for (Golden g : golden) {
            assertThat(model.tokenizer().encode(g.text(), model.maxLength()))
                    .as("ids for: %s", g.text()).containsExactly(g.ids());
        }
    }

    @Test
    @DisplayName("each vector agrees with sentence-transformers to cosine 0.99999 and 1e-4 per coordinate")
    void vectorsMatchReference() {
        assumeTrue(model != null, "embedding model not installed");
        float[][] ours = model.embed(golden.stream().map(Golden::text).toList());
        for (int i = 0; i < golden.size(); i++) {
            float[] ref = golden.get(i).vector();
            assertThat(ours[i]).hasSize(ref.length);
            assertThat(SentenceEmbedder.cosine(ours[i], ref)).as("cosine for: %s", golden.get(i).text())
                    .isGreaterThan(0.99999);
            for (int c = 0; c < ref.length; c++) {
                assertThat((double) Math.abs(ours[i][c] - ref[c])).isLessThan(1e-4);
            }
        }
    }

    @Test
    @DisplayName("similar answers are closer than different ones, which is the whole point")
    void meaningIsOrdered() {
        assumeTrue(model != null, "embedding model not installed");
        float[][] v = model.embed(List.of(
                "The bending moment is maximum where the shear force changes sign.",
                "Maximum BM occurs at the point of zero shear.",
                "Reynolds number above 4000 means the pipe flow is turbulent."));
        assertThat(SentenceEmbedder.cosine(v[0], v[1])).isGreaterThan(SentenceEmbedder.cosine(v[0], v[2]) + 0.2);
    }

    @Test
    @DisplayName("embedding is deterministic and repeat answers are served from memory")
    void deterministic() {
        assumeTrue(model != null, "embedding model not installed");
        float[][] a = model.embed(List.of("Same answer.", "Same answer."));
        float[][] b = model.embed(List.of("Same answer."));
        assertThat(a[0]).containsExactly(a[1]);
        assertThat(a[0]).containsExactly(b[0]);
    }
}
